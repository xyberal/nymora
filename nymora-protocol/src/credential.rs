    /// The full path-1 flow across two devices, per §9.3's ordering: the successor's root
    /// exists first, the old device authorizes, the successor completes.
    #[test]
    #[cfg(feature = "provisional-algebraic-hash")]
    fn planned_migration_carries_the_credential_key_and_spends_the_old_leaf() {
        let mut old_device = TestStore::default();
        let old = created(&mut old_device, AGORA_A);

        // Successor generates its root first; its public key travels to the old device.
        let successor_keys = SoftwareKeyStore::new([0x5b; 32]);
        let mut successor_pk = [0u8; 32];
        let mut binding = [0u8; 32];
        let written =
            create_successor_root(AGORA_A, &successor_keys, &mut successor_pk, &mut binding)
                .expect("root creation succeeds");
        let successor_pk = &successor_pk[..written.public_key];

        // Old device authorizes and emits the handoff.
        let mut old_pk = [0u8; 64];
        let mut signature = [0u8; 64];
        let mut handoff_bytes = [0u8; 256];
        let len = authorize_migration(
            AGORA_A,
            &key_store(),
            &old_device,
            successor_pk,
            &mut old_pk,
            &mut signature,
            &mut handoff_bytes,
        )
        .expect("authorization succeeds");

        // Successor decodes and completes. The consumed leaf is no longer carried — it is
        // derived from the handoff's witness material, and must equal the leaf created.
        let handoff = MigrationHandoff::decode(&handoff_bytes[..len]).expect("handoff decodes");
        assert_eq!(
            commit(
                handoff.root_public_key,
                &handoff.credential_key,
                &handoff.root_opening,
                &AGORA_A,
            ),
            old.commitment
        );

        let mut new_device = TestStore::default();
        let migrated = complete_migration(
            AGORA_A,
            &mut new_device,
            &handoff,
            successor_pk,
            entropy(0x23),
        )
        .expect("migration completes");

        // The spend is the per-leaf migration nullifier over the carried key.
        assert_eq!(
            migrated.spend,
            nullifier::migration(&CredentialKey::new([0x44; 32]), &old.commitment, &AGORA_A)
        );
        assert_ne!(migrated.commitment, old.commitment);

        // The successor holds the same sk_cred, a fresh opening, its own root.
        let mut sk = [0u8; 32];
        new_device
            .load(AGORA_A, Slot::CredentialKey, &mut sk)
            .unwrap()
            .expect("sk_cred carried over");
        assert_eq!(sk, [0x44; 32]);
    }

