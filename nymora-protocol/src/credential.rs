    /// The phase's exit criterion, in one test: the full lifecycle — create, certify,
    /// roll, migrate — across two agoras, on the reference backend and the test store,
    /// with the same entropy fed to both memberships adversarially. No value derived in
    /// one agora may equal its counterpart in the other, and the migration in one must
    /// leave the other untouched.
    #[test]
    #[cfg(feature = "provisional-algebraic-hash")]
    fn the_full_lifecycle_runs_in_two_agoras_without_a_shared_value() {
        let mut store = TestStore::default();

        // Same entropy into both agoras — the negative class is construction, not conduct.
        let first = created(&mut store, AGORA_A);
        let second = created(&mut store, AGORA_B);
        assert_ne!(first.commitment, second.commitment);

        let mut pk_a = [0u8; 32];
        let mut pk_b = [0u8; 32];
        let len_a = store
            .load(AGORA_A, Slot::RootPublicKey, &mut pk_a)
            .unwrap()
            .unwrap();
        let len_b = store
            .load(AGORA_B, Slot::RootPublicKey, &mut pk_b)
            .unwrap()
            .unwrap();
        assert_ne!(
            &pk_a[..len_a],
            &pk_b[..len_b],
            "one root key served two agoras"
        );

        // Certify and roll in both, same epoch numbers, same entropy.
        for agora in [AGORA_A, AGORA_B] {
            rolled(&mut store, agora, 1, 0xe1);
            rolled(&mut store, agora, 2, 0xe2);
            assert!(!store.holds(agora, Slot::EpochKey(Epoch::new(1))));
        }
        let mut buf_a = [0u8; 128];
        let mut buf_b = [0u8; 128];
        let record_a = load_epoch_record(AGORA_A, &store, Epoch::new(2), &mut buf_a)
            .unwrap()
            .unwrap();
        let record_b = load_epoch_record(AGORA_B, &store, Epoch::new(2), &mut buf_b)
            .unwrap()
            .unwrap();
        assert_ne!(
            record_a.signature, record_b.signature,
            "one epoch certificate served two agoras"
        );

        // Migrate in A; B must be untouched and share nothing with the result.
        let successor_keys = SoftwareKeyStore::new([0x5b; 32]);
        let mut successor_pk = [0u8; 32];
        let mut binding = [0u8; 32];
        let written =
            create_successor_root(AGORA_A, &successor_keys, &mut successor_pk, &mut binding)
                .unwrap();
        let successor_pk = &successor_pk[..written.public_key];

        let mut old_pk = [0u8; 64];
        let mut signature = [0u8; 64];
        let mut handoff_bytes = [0u8; 256];
        let len = authorize_migration(
            AGORA_A,
            &key_store(),
            &store,
            successor_pk,
            &mut old_pk,
            &mut signature,
            &mut handoff_bytes,
        )
        .unwrap();
        let handoff = MigrationHandoff::decode(&handoff_bytes[..len]).unwrap();

        let mut new_device = TestStore::default();
        let migrated = complete_migration(
            AGORA_A,
            &mut new_device,
            &handoff,
            successor_pk,
            entropy(0x23),
        )
        .unwrap();

        // The spend an identical adversarial migration in B would produce is unrelated.
        let consumed = commit(
            handoff.root_public_key,
            &handoff.credential_key,
            &handoff.root_opening,
            &AGORA_A,
        );
        let spend_in_b = nullifier::migration(&CredentialKey::new([0x44; 32]), &consumed, &AGORA_B);
        assert_ne!(migrated.spend, spend_in_b);
        assert_ne!(migrated.commitment, second.commitment);
        assert!(
            store.holds(AGORA_B, Slot::CredentialKey),
            "a migration in one agora touched another"
        );
        assert!(store.holds(AGORA_B, Slot::EpochKey(Epoch::new(2))));
    }

