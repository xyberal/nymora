    /// §9.1 / proposal 0007: however late the device wakes, ended epochs leave nothing
    /// usable behind.
    #[test]
    fn roll_sweeps_every_epoch_the_device_slept_through() {
        let mut store = TestStore::default();
        rolled(&mut store, AGORA_A, 3, 0xe1);
        rolled(&mut store, AGORA_A, 7, 0xe2);

        assert!(!store.holds(AGORA_A, Slot::EpochKey(Epoch::new(3))));
        assert!(!store.holds(AGORA_A, Slot::EpochCert(Epoch::new(3))));
        assert!(store.holds(AGORA_A, Slot::EpochKey(Epoch::new(7))));

        let swept: Vec<u64> = store
            .log
            .iter()
            .filter_map(|(op, slot)| match (op, slot) {
                ('d', Slot::EpochKey(e)) => Some(e.get()),
                _ => None,
            })
            .collect();
        assert_eq!(
            swept,
            vec![3, 4, 5, 6],
            "the sweep must cover the whole gap"
        );
    }

